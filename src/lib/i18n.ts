// CUE i18n — cookie-based locale. EN / ES / VI / AR. Arabic forces RTL.
// Dictionary keys are flat dotted strings; t() falls back to English then the key.
export const LOCALES = ["en", "es", "vi", "ar"] as const;
export type Locale = (typeof LOCALES)[number];
export const LOCALE_COOKIE = "cue_locale";
export const DEFAULT_LOCALE: Locale = "en";

export const LOCALE_LABELS: Record<Locale, string> = {
  en: "English",
  es: "Español",
  vi: "Tiếng Việt",
  ar: "العربية",
};

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

export function isRtl(locale: Locale): boolean {
  return locale === "ar";
}

